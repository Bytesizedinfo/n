#!/usr/bin/env python3
"""Generate js/manifest.js — the ordered list of every stylesheet and script the phone loads.

Run after adding or renaming a file:  python3 tools/manifest.py   (and: python3 tools/manifest.py --edition sunday)
The dev pages (index.html, sunday.html) and the bundler (tools/build.py) both use this order.

Editions share the phone (core, apps, art) and differ only in their story folder:
  default -> js/story         -> js/manifest.js
  sunday  -> js/story-sunday  -> js/manifest-sunday.js  ("Sunday at Lotus Pier", one connected narrative)
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

CORE = [
    'js/core/util.js', 'js/core/state.js', 'js/core/time.js', 'js/core/store.js', 'js/core/icons.js',
    'js/core/art.js', 'js/core/audio.js', 'js/core/keyboard.js', 'js/core/ui.js', 'js/core/notify.js',
    'js/core/os.js', 'js/core/story.js', 'js/data/contacts.js',
]


def listdir(rel, ext):
    d = os.path.join(ROOT, rel)
    if not os.path.isdir(d):
        return []
    return sorted(f'{rel}/{f}' for f in os.listdir(d) if f.endswith(ext) and not f.startswith('_'))


EDITIONS = {
    'default': {'story': 'js/story', 'out': 'js/manifest.js', 'pre': []},
    'sunday': {'story': 'js/story-sunday', 'out': 'js/manifest-sunday.js', 'pre': ['js/editions/sunday.js']},
}


def manifest(edition='default'):
    ed = EDITIONS[edition]
    st = ed['story']
    css = ['css/os.css', 'css/ui.css'] + listdir('css/apps', '.css')
    js = list(ed['pre']) + list(CORE)
    js += [f for f in listdir('js/data', '.js') if f not in js]
    js += listdir('js/art', '.js')
    js += listdir('js/apps', '.js')
    js += listdir(st + '/history', '.js')
    for f in [st + '/flavor.js', st + '/intro.js', st + '/table.js']:
        if os.path.exists(os.path.join(ROOT, f)):
            js.append(f)
    js += listdir(st + '/scenes', '.js')
    for f in [st + '/endings.js', st + '/dinner.js']:
        if os.path.exists(os.path.join(ROOT, f)):
            js.append(f)
    js.append('js/core/boot.js')
    css = [f for f in css if os.path.exists(os.path.join(ROOT, f))]
    js = [f for f in js if os.path.exists(os.path.join(ROOT, f))]
    return css, js


def edition_arg():
    if '--edition' in sys.argv:
        return sys.argv[sys.argv.index('--edition') + 1]
    return 'default'


def main():
    ed = edition_arg()
    css, js = manifest(ed)
    out = os.path.join(ROOT, EDITIONS[ed]['out'])
    body = '/* generated by tools/manifest.py — do not edit */\nwindow.JC_MANIFEST = ' + json.dumps({'css': css, 'js': js}, indent=1) + ';\n'
    with open(out, 'w') as f:
        f.write(body)
    if '-q' not in sys.argv:
        print(f'manifest ({ed}): {len(css)} css, {len(js)} js')


if __name__ == '__main__':
    main()
